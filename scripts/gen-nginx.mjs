#!/usr/bin/env node
/**
 * Generate nginx.conf from proxy-routes.mjs so the container serves exactly what
 * the dev server does.
 *
 * Run: npm run gen:nginx        (checked in — regenerate when routes change)
 *
 * The file it writes is generated. Edit proxy-routes.mjs, not nginx.conf: hand
 * edits are how the two tables drifted apart in the first place, which left the
 * production image serving a third of the data layers.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { ROUTES, SPECIAL } from '../proxy-routes.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'nginx.conf');

// nginx needs a resolver to look up upstream names at request time. Without it
// a proxy_pass to a variable-free https host is resolved once at startup, and a
// DNS change (or a container that starts later) is never picked up.
const HEAD = `# ─────────────────────────────────────────────────────────────────────────────
# GENERATED by scripts/gen-nginx.mjs from proxy-routes.mjs — do not edit.
# Regenerate with: npm run gen:nginx
#
# Every location below mirrors a dev-server proxy entry, so \`vite dev\` and the
# production container expose the same API surface. They used to be maintained
# separately and drifted badly.
# ─────────────────────────────────────────────────────────────────────────────

server {
    listen 80;
    server_name _;
    root /usr/share/nginx/html;
    index index.html;

    resolver 1.1.1.1 8.8.8.8 valid=300s ipv6=off;
    resolver_timeout 5s;

    # A dead upstream should look dead, not like a hung page.
    proxy_connect_timeout 5s;
    proxy_read_timeout 25s;

    # SPA fallback. Anything that is not a real file becomes index.html — which
    # is why a missing /api/* route returns HTML instead of JSON, and why a
    # forgotten proxy entry is so easy to miss.
    location / {
        try_files $uri $uri/ /index.html;
    }

    # The negative lookahead is load-bearing. A regex location OUTRANKS every
    # prefix location, so without it this rule captured any API route ending in
    # .json — /api/cctv/cctv/all.json was answered from the static root and 404'd
    # instead of ever reaching the upstream.
    location ~* ^(?!/api/).+\\.(js|css|png|jpg|jpeg|gif|ico|svg|woff|woff2|ttf|eot|json)$ {
        expires 1y;
        add_header Cache-Control "public, immutable";
    }
`;

// Headers that make several public endpoints return 403 when they arrive via a
// proxy or CDN. The dev server strips these too (`strip: true`).
const STRIP = ['Origin', 'Referer', 'Cookie', 'CF-Connecting-IP', 'CF-IPCountry',
               'CF-Ray', 'X-Forwarded-For', 'X-Forwarded-Proto', 'X-Forwarded-Host',
               'Sec-Fetch-Site', 'Sec-Fetch-Mode', 'Sec-Fetch-Dest'];

function hostOf(target) {
  return new URL(target).host;
}

function block(r) {
  const isTls = r.target.startsWith('https://');
  const lines = [];
  lines.push(`    # ${r.why}`);
  if (r.needs) lines.push(`    # requires ${r.needs}; without it the upstream answers with an error the layer surfaces`);
  if (r.internal) lines.push(`    # companion service — absent when running standalone; the layer degrades`);
  const loc = r.path.replace(/\/$/, '');
  lines.push(`    location ${loc} {`);
  // Strip the local prefix and graft on rewriteTo. Doing it with an explicit
  // rewrite (rather than a trailing slash on proxy_pass) behaves identically
  // whether or not the caller included a trailing slash.
  // ORDER MATTERS: `set` runs in the rewrite phase, and `rewrite ... break`
  // ends that phase — a `set` after the rewrite silently never executes and
  // every request 500s with "using uninitialized variable".
  lines.push(`        set $wv_upstream ${r.target};`);
  // Two explicit rules rather than one with an optional slash. A single
  // `^prefix/?(.*)$ -> /$1` turns a bare `/api/osint/rdns` into `/dns-query/`
  // WITH a trailing slash, and some upstreams answer that with a 301 instead of
  // the data.
  lines.push(`        rewrite ^${loc}$ ${r.rewriteTo || '/'} break;`);
  lines.push(`        rewrite ^${loc}/(.*)$ ${r.rewriteTo || ''}/$1 break;`);
  // proxy_pass via a VARIABLE, deliberately. With a literal hostname nginx
  // resolves at startup and REFUSES TO BOOT if the name is unknown — so one
  // absent companion service took the whole app down. A variable defers
  // resolution to request time (hence the `resolver` above): a missing upstream
  // becomes a 502 on that one route instead of a dead container.
  lines.push(`        proxy_pass $wv_upstream;`);
  lines.push(`        proxy_set_header Host ${hostOf(r.target)};`);
  if (isTls) lines.push(`        proxy_ssl_server_name on;`);
  for (const [k, v] of Object.entries(r.headers || {})) {
    lines.push(`        proxy_set_header ${k} "${v}";`);
  }
  if (r.strip) for (const h of STRIP) lines.push(`        proxy_set_header ${h} "";`);
  lines.push(`    }`);
  return lines.join('\n');
}

function specialBlock(r) {
  const lines = [];
  lines.push(`    # ${r.why}`);
  lines.push(`    # Credential is injected here so it never reaches the browser.`);
  lines.push(`    # ${r.needs} is templated into the config at container start (see docker-entrypoint.sh).`);
  const loc = r.path.replace(/\/$/, '');
  lines.push(`    location ${loc} {`);
  lines.push(`        set $wv_upstream ${r.target};`);
  lines.push(`        rewrite ^${loc}$ ${r.rewriteTo || '/'} break;`);
  lines.push(`        rewrite ^${loc}/(.*)$ ${r.rewriteTo || ''}/$1 break;`);
  lines.push(`        proxy_pass $wv_upstream;`);
  lines.push(`        proxy_set_header Host ${hostOf(r.target)};`);
  lines.push(`        proxy_ssl_server_name on;`);
  if (r.path.includes('wigle')) {
    lines.push(`        proxy_set_header Authorization "Basic \${WIGLE_API_TOKEN}";`);
    lines.push(`        proxy_cache wigle_cache;`);
    lines.push(`        proxy_cache_valid 200 2m;`);
    lines.push(`        proxy_cache_key $uri$is_args$args;`);
    lines.push(`        add_header X-Cache $upstream_cache_status;`);
    // The daily quota is per-account, not per-viewer: without this one open tab
    // per person is enough to exhaust it.
    lines.push(`        limit_req zone=wigle burst=3 nodelay;`);
  } else {
    lines.push(`        proxy_set_header Key "\${ABUSEIPDB_API_KEY}";`);
  }
  lines.push(`        proxy_set_header Accept "application/json";`);
  lines.push(`    }`);
  return lines.join('\n');
}

const body = [
  ...ROUTES.map(block),
  ...SPECIAL.map(specialBlock),
].join('\n\n');

const TAIL = `
    gzip on;
    gzip_types text/plain text/css application/json application/javascript text/xml;
}
`;

// The cache and rate-limit zones must be declared at http{} scope, which in the
// nginx:alpine image means a separate file included before conf.d/*.
const ZONES = `# GENERATED by scripts/gen-nginx.mjs — do not edit.
# http{}-scope directives for the WiGLE gate. Included before conf.d/default.conf.
proxy_cache_path /var/cache/nginx/wigle levels=1:2 keys_zone=wigle_cache:5m max_size=64m inactive=10m use_temp_path=off;
limit_req_zone $binary_remote_addr zone=wigle:1m rate=10r/m;
`;

writeFileSync(out, HEAD + '\n' + body + '\n' + TAIL);
writeFileSync(join(here, '..', '00-zones.conf'), ZONES);

const keyless = ROUTES.filter((r) => !r.needs && !r.internal).length;
console.log(`wrote nginx.conf — ${ROUTES.length + SPECIAL.length} routes ` +
            `(${keyless} need no credential, ${ROUTES.filter((r) => r.internal).length} companion)`);
console.log('wrote 00-zones.conf');
